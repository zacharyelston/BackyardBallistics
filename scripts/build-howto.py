"""Renders docs/howto/*.md and docs/howto/field.svg from docs/howto/src and the code's facts.

Called by scripts/build-howto.sh with the JSON that `spud-docs` printed. Placeholders in the
sources look like {{safety.fanRangeM}} (a fact) or {{orders_table}} (a generated block).
"""
import json, math, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "docs", "howto", "src")
OUT = os.path.join(ROOT, "docs", "howto")
HEADER = "<!-- Generated by scripts/build-howto.sh from docs/howto/src and the code. Edit the source, not this file. -->\n\n"


def fail(msg):
    sys.exit(f"build-howto: {msg}")


def num(x):
    """Plain numbers: 96.0 -> 96, 91.4 -> 91.4, 3.5999999 -> 3.6."""
    if isinstance(x, bool) or not isinstance(x, (int, float)):
        return str(x)
    r = round(float(x), 2)
    return str(int(r)) if r == int(r) else f"{r:g}"


def lookup(facts, path):
    v = facts
    for part in path.split("."):
        if not isinstance(v, dict) or part not in v:
            fail(f"unknown fact {{{{{path}}}}}")
        v = v[part]
    return v


def swift_switch(path, func_marker, pattern):
    """Pulls `case .a, .b: <value>` lines out of the first switch after `func_marker` in a Swift file."""
    text = open(os.path.join(ROOT, path)).read()
    start = text.find(func_marker)
    if start < 0:
        fail(f"can't find {func_marker!r} in {path}")
    body = text[start:text.find("\n    }\n", start)]
    out = {}
    for cases, value in re.findall(r"case ((?:\.\w+,?\s*)+):\s*" + pattern, body):
        for c in re.findall(r"\.(\w+)", cases):
            out[c] = value
    return out


def order_rows(facts):
    kinds = facts["squadz"]["orders"]
    icons = swift_switch("App/Shared/SiteMap.swift", "var systemImage: String", r'return "([^"]+)"')
    tools = swift_switch("App/Sources/Features/Squadz/OrderCard.swift", "init(_ order: Order)", r"self = ([^\n]+)")
    places = re.search(r"var takesPlace: Bool \{ (.+?) \}", open(os.path.join(ROOT, "App/Shared/SiteMap.swift")).read())
    takes_place = set(re.findall(r"\.(\w+)", places.group(1))) if places else set()
    names = {".ranging": "the ranging screen", ".goTo": "Go there (pointer and map)", ".spotting": "the spotter card",
             ".none": "nothing (read it and answer)"}
    rows = []
    for k in kinds:
        kind = k["kind"]
        if kind not in icons or kind not in tools:
            fail(f"order kind {kind} is missing from the app's icon or tool table; update OrderCard.swift / SiteMap.swift")
        tool = tools[kind].strip()
        if "?" in tool:   # `order.at == nil ? .none : .goTo`
            opens = "Go there (pointer and map), when it has a place"
        else:
            opens = names.get(tool, tool)
        rows.append((k["title"], icons[kind], "yes" if kind in takes_place else "", opens))
    return rows


def blocks(facts):
    rows = order_rows(facts)
    table = ["| Order | Icon (SF Symbol) | Takes a place | Seen opens |", "| --- | --- | --- | --- |"]
    table += [f"| {t} | `{i}` | {p} | {o} |" for t, i, p, o in rows]
    holds = [f"- {h}" for h in facts["squadz"]["holds"]]
    calls = ", ".join(f"**{c}**" for c in facts["rules"]["rangeCalls"])
    return {
        "orders_table": "\n".join(table),
        "holds_list": "\n".join(holds),
        "range_calls": calls,
        "order_answers": ", ".join(f"**{a}**" for a in facts["squadz"]["orderAnswers"]).replace("cannot", "can't"),
    }


def render(text, facts, generated):
    def sub(m):
        key = m.group(1)
        if key in generated:
            return generated[key]
        return num(lookup(facts, key))
    return re.sub(r"\{\{([\w.]+)\}\}", sub, text)


def field_svg(facts):
    """The field from above: boundary, firing point, fan, flag and ring, and where the squad stands."""
    hole = facts["course"]["hole"]
    fan_r, half = facts["safety"]["fanRangeM"], facts["safety"]["fanHalfAngleDeg"]
    brg = hole["bearingDeg"]
    pts = hole["boundaryEN"] + [[0, 0], hole["flagEN"]]
    for a in (-half, 0, half):
        b = math.radians(brg + a)
        pts.append([fan_r * math.sin(b), fan_r * math.cos(b)])
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    pad = 14
    minx, maxx, miny, maxy = min(xs) - pad, max(xs) + pad, min(ys) - pad, max(ys) + pad
    W = 640
    s = W / (maxx - minx)
    H = round((maxy - miny) * s) + 70
    X = lambda e: round((e - minx) * s, 1)
    Y = lambda n: round((maxy - n) * s + 50, 1)
    def P(p): return f"{X(p[0])},{Y(p[1])}"
    fan = [[0, 0]] + [[fan_r * math.sin(math.radians(brg + a)), fan_r * math.cos(math.radians(brg + a))]
                      for a in range(-int(half), int(half) + 1, 3)]
    left = math.radians(brg - 90)
    spotter = [12 * math.sin(left) - 2 * math.sin(math.radians(brg)), 12 * math.cos(left) - 2 * math.cos(math.radians(brg))]
    ipad = [-4 * math.sin(math.radians(brg)) + 3 * math.cos(math.radians(brg)), -4 * math.cos(math.radians(brg))]
    fx, fy = hole["flagEN"]
    ring = max(3, hole["ringM"] * s)
    bar = 20 * s
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="-apple-system,Helvetica,Arial,sans-serif" font-size="13">
<!-- Generated by scripts/build-howto.sh from SafetyKit's limits and courses/sample-course.yaml. -->
<rect width="{W}" height="{H}" fill="#f3f6ef"/>
<text x="14" y="22" font-weight="700" font-size="15">{facts['course']['name']}: hole {hole['number']}, {hole['name']} (par {hole['par']}, {num(hole['distanceM'])} m)</text>
<text x="14" y="40" fill="#555">North is up. Red: the safety fan ({num(fan_r)} m, ±{num(half)}°) must stay inside the boundary.</text>
<polygon points="{' '.join(P(p) for p in hole['boundaryEN'])}" fill="#dfeccf" stroke="#4d7a2a" stroke-width="2"/>
<polygon points="{' '.join(P(p) for p in fan)}" fill="#e03131" fill-opacity="0.13" stroke="#e03131" stroke-dasharray="6 4"/>
<line x1="{X(0)}" y1="{Y(0)}" x2="{X(fx)}" y2="{Y(fy)}" stroke="#333" stroke-dasharray="4 4"/>
<circle cx="{X(fx)}" cy="{Y(fy)}" r="{ring}" fill="#2f9e44" fill-opacity="0.35" stroke="#2f9e44"/>
<line x1="{X(fx)}" y1="{Y(fy)}" x2="{X(fx)}" y2="{Y(fy) - 26}" stroke="#333" stroke-width="2"/>
<polygon points="{X(fx)},{Y(fy) - 26} {X(fx) + 14},{Y(fy) - 21} {X(fx)},{Y(fy) - 16}" fill="#e03131"/>
<text x="{X(fx) + 16}" y="{Y(fy) - 8}">Pole and ring ({num(hole['ringM'])} m)</text>
<polygon points="{X(0) - 7},{Y(0) + 6} {X(0) + 7},{Y(0) + 6} {X(0)},{Y(0) - 7}" fill="#1c7ed6"/>
<text x="{X(0) + 12}" y="{Y(0) + 4}" fill="#1c7ed6">Firing point: gunner</text>
<circle cx="{X(spotter[0])}" cy="{Y(spotter[1])}" r="6" fill="#f08c00" stroke="#fff" stroke-width="2"/>
<text x="{X(spotter[0]) - 8}" y="{Y(spotter[1]) + 20}" text-anchor="end" fill="#b35c00">Spotter (flank)</text>
<rect x="{X(ipad[0]) - 8}" y="{Y(ipad[1]) - 6}" width="16" height="12" rx="2" fill="#495057"/>
<text x="{X(ipad[0]) + 12}" y="{Y(ipad[1]) + 18}" fill="#495057">Commander's iPad</text>
<line x1="14" y1="{H - 14}" x2="{14 + bar:.1f}" y2="{H - 14}" stroke="#333" stroke-width="2"/>
<text x="14" y="{H - 20}">20 m</text>
</svg>
"""


def main():
    if len(sys.argv) < 2:
        fail("usage: build-howto.py facts.json [--check]")
    facts = json.load(open(sys.argv[1]))
    check = "--check" in sys.argv[2:]
    generated = blocks(facts)
    outputs = {"field.svg": field_svg(facts)}
    for name in sorted(os.listdir(SRC)):
        if name.endswith(".md"):
            outputs[name] = HEADER + render(open(os.path.join(SRC, name)).read(), facts, generated)
    stale = []
    for name, text in outputs.items():
        path = os.path.join(OUT, name)
        old = open(path).read() if os.path.exists(path) else None
        if old != text:
            stale.append(name)
            if not check:
                with open(path, "w") as f:
                    f.write(text)
    if check and stale:
        fail("out of date: " + ", ".join(stale) + ". Run scripts/build-howto.sh and commit.")
    print(("up to date" if not stale else "wrote " + ", ".join(stale)) if not check else "docs/howto is up to date")


main()
